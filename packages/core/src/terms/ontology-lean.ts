// Writes Reflect's ontology (ontology.json) as a Lean file, lean/Reflect/Generated/Ontology.lean, the way
// tchjhnsn/naive writes packages/naive/lean/Naive/Generated/Ontology.lean. scripts/ontology-lean.ts runs it and
// `--check` fails when the committed file is stale; ontology-lean.test.ts does the same in the test run.
//
// What the file holds: Aristotle's ten Categories and the kept nouns as Lean inductive types, each noun's broader
// nouns and broader categories, and a certificate (each noun's rank, the number of broader nouns above it on its
// longest path, and its category, from checkOntology). lean/Reflect/Hierarchy.lean proves that when the checker
// passes on these, the broader relation has no cycle and each noun reaches exactly one category. The kernel checks
// the certificate by `decide`, so a wrong one fails the Lean build; it cannot prove something false.
//
// Names: a noun becomes lower camel case from its ASCII letter and digit runs ("friend group" is friendGroup), in
// Lean's «» quotes so a keyword such as `end` still parses. Two nouns with one name, or an ontology that fails
// checkOntology, stop the run. Each noun's meaning, standard, app and kinds go in its docstring, so editing any of
// them changes the file.
import { CATEGORIES, checkOntology, type Ontology } from "./ontology.ts";

export const LEAN_ONTOLOGY_PATH = "lean/Reflect/Generated/Ontology.lean";

const camel = (text: string): string => {
  const words = text.match(/[A-Za-z0-9]+/g) ?? [];
  return words.map((w, i) => (i === 0 ? w.toLowerCase() : w[0]!.toUpperCase() + w.slice(1).toLowerCase())).join("");
};

/** The Lean name of a noun or category, without the «» quotes. */
export function leanName(text: string): string {
  const name = camel(text);
  if (name === "") throw new Error(`"${text}" has no letters or digits to name it in Lean`);
  return name;
}

// A docstring may not hold the closing token of a comment.
const doc = (text: string): string => text.replace(/-\//g, "- /").replace(/\s+/g, " ").trim();
const str = (text: string): string => JSON.stringify(text);
const q = (name: string): string => `«${name}»`;

/** The Lean file for an ontology. Throws when the ontology fails its check or two names collide. */
export function leanOntology(o: Ontology): string {
  // The kinds rules (K1, K2) need the life kinds and do not bear on the hierarchy, so they are left to ontology.test.ts.
  const verdict = checkOntology(o, []);
  const problems = verdict.problems.filter((p) => !p.startsWith("K"));
  const { categoryOf } = verdict;
  if (problems.length > 0) throw new Error(`the ontology fails its check:\n${problems.join("\n")}`);
  const nouns = o.nouns.filter((n) => n.status !== "retired");
  const names = new Map<string, string>();
  for (const n of nouns) {
    const name = leanName(n.noun);
    const clash = [...names].find(([, v]) => v === name);
    if (clash) throw new Error(`nouns "${clash[0]}" and "${n.noun}" are both ${name} in Lean`);
    names.set(n.noun, name);
  }
  const tops = new Set<string>(CATEGORIES);
  const rank = new Map<string, number>();
  const rankOf = (noun: string): number => {
    const known = rank.get(noun);
    if (known !== undefined) return known;
    const above = nouns.find((n) => n.noun === noun)!.broader.filter((b) => !tops.has(b));
    const r = above.length === 0 ? 0 : 1 + Math.max(...above.map(rankOf));
    rank.set(noun, r);
    return r;
  };
  const N = (noun: string): string => `.${q(names.get(noun)!)}`;
  const C = (cat: string): string => `.${q(leanName(cat))}`;
  const byNoun = (fn: string, type: string, value: (n: (typeof nouns)[number]) => string): string[] => [
    `def Noun.${fn} : Noun → ${type}`,
    ...nouns.map((n) => `  | ${N(n.noun)} => ${value(n)}`),
    "",
  ];
  const categoryDoc = new Map(o.top_categories.map((t) => [t.name, t]));

  return [
    "import Reflect.Hierarchy",
    "",
    "/-",
    "  Generated by scripts/ontology-lean.ts from packages/core/src/terms/ontology.json. Do not edit: change the",
    "  ontology and run `node scripts/ontology-lean.ts`. The ten Categories and the kept nouns, each noun's broader",
    "  links, and a certificate (rank and category) that `certified` checks by `decide`. Reflect/Categories.lean",
    "  draws the theorems from it.",
    "-/",
    "",
    "namespace Reflect.Ontology",
    "",
    "/-- [D] Aristotle's ten Categories, in his order (Categories 4, 1b25-2a4). -/",
    "inductive Category",
    ...CATEGORIES.map((c) => {
      const t = categoryDoc.get(c);
      return `  /-- ${doc(`${c} (${t?.greek ?? ""}, BFO ${t?.bfo.class ?? ""}). ${t?.meaning ?? ""}`)} -/\n  | ${q(leanName(c))}`;
    }),
    "  deriving DecidableEq, Repr",
    "",
    "/-- [D] The kept nouns of the ontology. -/",
    "inductive Noun",
    ...nouns.map(
      (n) =>
        `  /-- ${doc(`${n.noun} (${n.status}; app ${n.app ?? "shared"}; kinds ${n.kinds.length > 0 ? n.kinds.join(", ") : "none"}). ${n.meaning} Standard: ${n.standard}.`)} -/\n  | ${q(names.get(n.noun)!)}`,
    ),
    "  deriving DecidableEq, Repr",
    "",
    "/-- [D] A category's name in ontology.json. -/",
    "def Category.name : Category → String",
    ...CATEGORIES.map((c) => `  | ${C(c)} => ${str(c)}`),
    "",
    "/-- [D] A noun's name in ontology.json. -/",
    ...byNoun("name", "String", (n) => str(n.noun)),
    "/-- [D] Every noun, once. -/",
    `def Noun.all : List Noun := [${nouns.map((n) => N(n.noun)).join(", ")}]`,
    "",
    "/-- [D] The nouns a noun names in broader. -/",
    ...byNoun("broaderNouns", "List Noun", (n) => `[${n.broader.filter((b) => !tops.has(b)).map(N).join(", ")}]`),
    "/-- [D] The categories a noun names in broader. -/",
    ...byNoun("broaderCategories", "List Category", (n) => `[${n.broader.filter((b) => tops.has(b)).map(C).join(", ")}]`),
    "/-- [D] Certificate: the number of broader nouns above a noun on its longest path. -/",
    ...byNoun("rank", "Nat", (n) => String(rankOf(n.noun))),
    "/-- [D] Certificate: the category a noun reaches. -/",
    ...byNoun("category", "Category", (n) => C(categoryOf.get(n.noun)!)),
    "/-- [D] The broader links as a hierarchy. -/",
    "def hierarchy : Hierarchy Category Noun := ⟨Noun.broaderNouns, Noun.broaderCategories⟩",
    "",
    "/-- `Noun.all` lists every noun. -/",
    "theorem Noun.mem_all (n : Noun) : n ∈ Noun.all := by cases n <;> decide",
    "",
    "/-- The checker passes on the ontology with its certificate. -/",
    "theorem certified : hierarchy.Certified Noun.all Noun.rank Noun.category = true := by decide",
    "",
    "end Reflect.Ontology",
    "",
  ].join("\n");
}
