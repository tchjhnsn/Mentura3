// virtu build: the act capability of D1. It turns a declaration that passes
// check into files an app imports: virtu.css (one custom property per token,
// with one attribute rule per context value), virtu.tailwind.css (a Tailwind
// v4 theme over those properties), virtu.tokens.json (every token under
// every permutation), and with the shadcn target virtu.shadcn.css (shadcn/ui's
// variables as aliases of the properties). build() is pure and imports
// nothing from Node; writeBuild() in write.ts is the only I/O. A declaration
// that fails check, or whose names cannot become CSS names, builds nothing.
// previewCss() is the one exception: virtu editor shows a failing edit on the
// page while a person works, and that CSS is never written.

