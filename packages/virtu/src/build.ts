/** The first line of every CSS file build writes. virtu audit skips files that start with it. */
export const GENERATED_HEADER = "/* Generated by virtu build. Do not edit. */";

export const BUILD_FILES = ["virtu.css", "virtu.tailwind.css", "virtu.tokens.json", "virtu.shadcn.css"] as const;
export type BuildFileName = (typeof BUILD_FILES)[number];
export type BuildFile = { name: BuildFileName; content: string };

/** A token that has no CSS form, or loses part of its value in CSS. */
export type BuildNote = { token: string; type: string | null; note: string };

export type BuildResult =
  | { ok: true; files: BuildFile[]; findings: Finding[]; notes: BuildNote[]; properties: number; tailwindNames: number; permutations: number; shadcnVariables: number }
  | { ok: false; reason: "check"; check: CheckResult }
  | { ok: false; reason: "names" | "shadcn"; findings: Finding[] };

/** What else to write. shadcn: the system's shadcn.virtu.json, read by loadShadcnMap, for virtu.shadcn.css. */
export type BuildOptions = { shadcn?: ShadcnMap };

const PREFIX = "--virtu-";

/** The CSS custom property for a token path: dots become hyphens, and a DTCG $root segment is dropped. */
export function cssName(path: string): string {
  return PREFIX + segments(path).join("-");
}

function segments(path: string): string[] {
  return path.split(".").filter((s) => s !== "$root");
}

/** Characters a CSS custom property name may hold without escaping. */
function safeIdent(text: string): boolean {
  if (text === "") return false;
  for (const ch of text) {
    const code = ch.codePointAt(0) ?? 0;
    if (code >= 0x80) continue;
    if (!/[A-Za-z0-9_-]/.test(ch)) return false;
  }
  return true;
}

/** Tailwind v4 namespaces, by the token's domain and DTCG type. A pair not listed has no Tailwind name. */
export const TAILWIND_NAMESPACES: ReadonlyArray<{ domain: DomainId; type: TokenType; prefix: string }> = [
  { domain: "color", type: "color", prefix: "--color-" },
  { domain: "space", type: "dimension", prefix: "--spacing-" },
  { domain: "typography", type: "dimension", prefix: "--text-" },
  { domain: "typography", type: "fontFamily", prefix: "--font-" },
  { domain: "typography", type: "fontWeight", prefix: "--font-weight-" },
  { domain: "depth", type: "shadow", prefix: "--shadow-" },
  { domain: "motion", type: "cubicBezier", prefix: "--ease-" },
];

/** The Tailwind theme variable for a token: the namespace, then the token path without its first segment. */
export function tailwindName(path: string, domain: DomainId | null, type: TokenType | null): string | null {
  const ns = TAILWIND_NAMESPACES.find((n) => n.domain === domain && n.type === type);
  if (!ns) return null;
  const rest = segments(path).slice(1);
  return rest.length === 0 ? null : ns.prefix + rest.join("-");
}

const byCodeUnit = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

// CSS values.

/**
 * A token's CSS value. wide is set for a color written in a wider space with
 * a hex fallback: css is then the fallback, and wide the color itself, which
 * virtu.css gives only to screens that can show it.
 */
type CssValue = { css: string; note: string | null; wide?: string } | { css: null; note: string };

/** A number in CSS: at most four decimals, no trailing zeros, never -0. */
function num(n: number): string {
  const r = Math.round(n * 10000) / 10000;
  return String(r === 0 ? 0 : r);
}

export function cssColor(c: Color): string {
  const hasNone = c.components.includes("none");
  if (c.space === "srgb" && !hasNone) {
    if (c.alpha >= 1) return colorToHex(c) ?? "";
    const byte = (x: number | "none"): string => String(Math.round((x === "none" ? 0 : x) * 255));
    return `rgb(${c.components.map(byte).join(" ")} / ${num(c.alpha)})`;
  }
  const comp = (x: number | "none", percent: boolean): string => (x === "none" ? "none" : `${num(x)}${percent ? "%" : ""}`);
  const alpha = c.alpha < 1 ? ` / ${num(c.alpha)}` : "";
  const [a = "none", b = "none", d = "none"] = c.components;
  switch (c.space) {
    case "hsl":
    case "hwb":
      return `${c.space}(${comp(a, false)} ${comp(b, true)} ${comp(d, true)}${alpha})`;
    case "lab":
    case "lch":
    case "oklab":
    case "oklch":
      return `${c.space}(${comp(a, false)} ${comp(b, false)} ${comp(d, false)}${alpha})`;
    default:
      return `color(${c.space} ${comp(a, false)} ${comp(b, false)} ${comp(d, false)}${alpha})`;
  }
}

const dimension = (d: Dimension): string => `${num(d.value)}${d.unit}`;
const durationMs = (d: { value: number; unit: "ms" | "s" }): string => `${num(d.unit === "s" ? d.value * 1000 : d.value)}ms`;

const GENERIC_FAMILIES = new Set([
  "serif",
  "sans-serif",
  "monospace",
  "cursive",
  "fantasy",
  "system-ui",
  "ui-serif",
  "ui-sans-serif",
  "ui-monospace",
  "ui-rounded",
  "math",
  "emoji",
  "fangsong",
]);

function fontFamilies(families: string[]): string {
  return families.map((f) => (GENERIC_FAMILIES.has(f) ? f : `"${f.replace(/["\\]/g, (m) => `\\${m}`)}"`)).join(", ");
}

function shadowCss(raw: Json | null): string | null {
  const layers = Array.isArray(raw) ? raw : [raw];
  const parts: string[] = [];
  for (const layer of layers) {
    if (!isObject(layer)) return null;
    const color = parseColor(layer["color"] ?? null);
    if (typeof color === "string") return null;
    const sizes: string[] = [];
    for (const key of ["offsetX", "offsetY", "blur", "spread"]) {
      const d = parseDimension(layer[key] ?? null);
      if (typeof d === "string") return null;
      sizes.push(dimension(d));
    }
    parts.push(`${layer["inset"] === true ? "inset " : ""}${sizes.join(" ")} ${cssColor(color)}`);
  }
  return parts.join(", ");
}

/** The CSS value of a resolved token, or why it has none. */
export function cssValue(token: ResolvedToken): CssValue {
  const v = token.value;
  if (v === null) return { css: null, note: "the token does not resolve" };
  switch (v.type) {
    case "color": {
      const c = v.color;
      if (c.space === "srgb" || c.hex === undefined) return { css: cssColor(c), note: null };
      const fallback: Color = { space: "srgb", components: [1, 3, 5].map((i) => parseInt(c.hex?.slice(i, i + 2) ?? "00", 16) / 255), alpha: c.alpha };
      return { css: cssColor(fallback), note: null, wide: cssColor(c) };
    }
    case "dimension":
      return { css: dimension(v.dimension), note: null };
    case "duration":
      return { css: durationMs(v.duration), note: null };
    case "number":
      return { css: num(v.number), note: null };
    case "fontFamily":
      return { css: fontFamilies(v.families), note: null };
    case "fontWeight":
      return { css: String(v.weight), note: null };
    case "cubicBezier":
      return { css: `cubic-bezier(${v.points.map(num).join(", ")})`, note: null };
    case "shadow": {
      const css = shadowCss(token.raw);
      return css === null ? { css: null, note: "the shadow has no CSS form" } : { css, note: null };
    }
    case "typography": {
      const raw = token.raw;
      if (!isObject(raw)) return { css: null, note: "the typography value has no CSS form" };
      const family = raw["fontFamily"];
      const families = typeof family === "string" ? [family] : Array.isArray(family) ? family.filter((f): f is string => typeof f === "string") : [];
      const weight = raw["fontWeight"];
      const line = raw["lineHeight"];
      if (families.length === 0 || typeof line !== "number") return { css: null, note: "the typography value has no CSS form" };
      const w = typeof weight === "number" ? String(weight) : "normal";
      const css = `${w} ${dimension(v.fontSize)}/${num(line)} ${fontFamilies(families)}`;
      return { css, note: "letterSpacing" in raw ? "written as the font shorthand, which cannot hold letterSpacing; letterSpacing is left out" : null };
    }
    case "transition": {
      const raw = token.raw;
      if (!isObject(raw)) return { css: null, note: "the transition has no CSS form" };
      const duration = parseDuration(raw["duration"] ?? null);
      const delay = parseDuration(raw["delay"] ?? null);
      const tf = raw["timingFunction"];
      if (typeof duration === "string" || typeof delay === "string" || !Array.isArray(tf)) return { css: null, note: "the transition has no CSS form" };
      const points = tf.filter((n): n is number => typeof n === "number").map(num);
      return { css: `${durationMs(duration)} cubic-bezier(${points.join(", ")}) ${durationMs(delay)}`, note: null };
    }
    default:
      return { css: null, note: `version 0 writes no CSS for a ${v.type} token` };
  }
}

// The build.

type Values = Map<string, string>;

export function build(loaded: Loaded, options: BuildOptions = {}): BuildResult {
  const outcome = check(loaded);
  if (outcome.verdict === "fail") return { ok: false, reason: "check", check: outcome };
  return compose(loaded, outcome.findings, options);
}

/**
 * virtu.css for a declaration whether or not it passes check, or null when
 * its names cannot become CSS names. virtu editor puts it on the page so a
 * person sees a failing edit before fixing it. Nothing writes it to a file.
 */
export function previewCss(loaded: Loaded): string | null {
  const r = compose(loaded, [], {});
  if (!r.ok) return null;
  return r.files.find((f) => f.name === "virtu.css")?.content ?? null;
}

/** Everything build() does after check passes. checked: check's findings, which the result carries. */
function compose(loaded: Loaded, checked: Finding[], options: BuildOptions): BuildResult {
  const a = analyze(loaded);

  // Every token's CSS value under every permutation, and the notes for tokens without one.
  const values = new Map<string, Values>();
  // The wide values (Display P3 and other spaces with a hex fallback), by permutation.
  const wides = new Map<string, Values>();
  const tokens = new Map<string, ResolvedToken>();
  const notes = new Map<string, BuildNote>();
  for (const p of a.permutations) {
    const vals: Values = new Map();
    const wideVals: Values = new Map();
    for (const token of a.resolution(p).tokens.values()) {
      if (!tokens.has(token.path)) tokens.set(token.path, token);
      const v = cssValue(token);
      if (v.note !== null && !notes.has(token.path)) notes.set(token.path, { token: token.path, type: token.type, note: v.note });
      if (v.css !== null) vals.set(token.path, v.css);
      if (v.css !== null && v.wide !== undefined) wideVals.set(token.path, v.wide);
    }
    values.set(permutationKey(p), vals);
    wides.set(permutationKey(p), wideVals);
  }
  const paths = [...new Set([...values.values()].flatMap((v) => [...v.keys()]))].sort(byCodeUnit);

  // Names: every one must be a plain CSS identifier, and no two tokens may share one.
  const nameFindings: Finding[] = [];
  const cssNames = new Map<string, string>();
  const twNames = new Map<string, { path: string; name: string }>();
  for (const path of paths) {
    const name = cssName(path);
    if (!safeIdent(name.slice(2))) {
      nameFindings.push(buildFinding("build.name-unsafe", `${path} cannot become a CSS custom property name: use letters, digits, - and _ in token names`, [path]));
      continue;
    }
    const other = cssNames.get(name);
    if (other !== undefined) {
      nameFindings.push(buildFinding("build.name-collision", `${other} and ${path} would both be ${name}`, [other, path]));
      continue;
    }
    cssNames.set(name, path);
    const token = tokens.get(path);
    const tw = tailwindName(path, a.domainOfToken(path), token?.type ?? null);
    if (tw === null) continue;
    const prev = twNames.get(tw);
    if (prev !== undefined) {
      nameFindings.push(buildFinding("build.name-collision", `${prev.path} and ${path} would both be the Tailwind name ${tw}`, [prev.path, path]));
      continue;
    }
    twNames.set(tw, { path, name });
  }
  for (const c of a.contexts) {
    if (!/^[a-z][a-z0-9_-]*$/.test(c.name)) {
      nameFindings.push(buildFinding("build.name-unsafe", `context ${c.name} cannot become a data- attribute: use lowercase letters, digits, - and _`, [c.name]));
    }
  }
  if (nameFindings.length > 0) return { ok: false, reason: "names", findings: nameFindings };
  const shadcn = options.shadcn === undefined ? null : planShadcn(a, options.shadcn);
  if (shadcn !== null && !shadcn.ok) return { ok: false, reason: "shadcn", findings: shadcn.findings };

  const contexts = contextList(a).filter((c) => c.values.length > 0);
  const def = a.defaultPermutation;
  const base = values.get(permutationKey(def)) ?? new Map<string, string>();

  // What each context value changes, against the default permutation.
  const overlays = new Map<string, Map<string, Values>>();
  for (const c of contexts) {
    const byValue = new Map<string, Values>();
    for (const value of c.values) {
      const vals = values.get(permutationKey({ ...def, [c.name]: value })) ?? new Map<string, string>();
      const changed: Values = new Map();
      for (const [path, css] of vals) if (base.get(path) !== css) changed.set(path, css);
      byValue.set(value, changed);
    }
    overlays.set(c.name, byValue);
  }

  // A token two contexts change, or one the overlays cannot reproduce, gets a warning.
  const findings: Finding[] = checked.slice();
  const warned = new Set<string>();
  const changedBy = new Map<string, Set<string>>();
  for (const [ctx, byValue] of overlays) {
    for (const vals of byValue.values()) {
      for (const path of vals.keys()) changedBy.set(path, (changedBy.get(path) ?? new Set<string>()).add(ctx));
    }
  }
  for (const [path, ctxs] of changedBy) {
    if (ctxs.size < 2) continue;
    warned.add(path);
    findings.push(
      buildFinding(
        "build.context-interaction",
        `${path} is changed by ${[...ctxs].join(" and ")}; where both attributes are set, virtu.css gives the value of the one nearer the element`,
        [path],
      ),
    );
  }
  for (const p of a.permutations) {
    const actual = values.get(permutationKey(p)) ?? new Map<string, string>();
    const composed = new Map(base);
    for (const c of contexts) {
      const value = p[c.name];
      if (value === undefined) continue;
      for (const [path, css] of overlays.get(c.name)?.get(value) ?? []) composed.set(path, css);
    }
    for (const path of new Set([...actual.keys(), ...composed.keys()])) {
      if (warned.has(path) || actual.get(path) === composed.get(path)) continue;
      warned.add(path);
      findings.push(
        buildFinding(
          "build.context-interaction",
          `under ${formatPermutation(p)}, ${path} is ${actual.get(path) ?? "absent"} but virtu.css gives ${composed.get(path) ?? "nothing"}, because its value depends on more than one context`,
          [path],
          p,
        ),
      );
    }
  }

  // virtu.css: the rules in cascade order, each with the permutation whose values it holds.
  const rules: Array<{ selector: string; perm: Permutation; vals: Values }> = [{ selector: ":root", perm: def, vals: base }];
  for (const c of contexts) {
    const byValue = overlays.get(c.name) ?? new Map<string, Values>();
    // A propagating context can be set again deeper down, so its default value
    // needs a rule too: it restores the tokens the other values change.
    const restore: Values = new Map();
    if (c.dialect === "propagating") {
      for (const vals of byValue.values()) {
        for (const path of vals.keys()) {
          const css = base.get(path);
          if (css !== undefined) restore.set(path, css);
        }
      }
    }
    for (const value of c.values) {
      const vals = value === c.default ? restore : (byValue.get(value) ?? new Map<string, string>());
      if (vals.size === 0) continue;
      rules.push({ selector: `[data-${c.name}="${value.replace(/["\\]/g, (m) => `\\${m}`)}"]`, perm: { ...def, [c.name]: value }, vals });
    }
  }
  const css: string[] = [GENERATED_HEADER];
  const described = contexts.map((c) => `${c.name} (${c.dialect ?? "no dialect"}, default ${c.default ?? "none"})`).join(", ");
  css.push(`/* System: ${loaded.name}. Contexts: ${described || "none"}. */`);
  for (const r of rules) {
    css.push("");
    css.push(rule(r.selector, r.vals));
  }
  const wideBlock = wideRules(rules, wides, values, def);
  if (wideBlock.length > 0) {
    css.push("");
    css.push("/* Display P3 values, for screens that can show them. Every other screen keeps the sRGB fallbacks above. */");
    css.push("@supports (color: color(display-p3 0 0 0)) {");
    css.push("  @media (color-gamut: p3) {");
    css.push(wideBlock.map((r) => rule(r.selector, r.vals).replace(/^/gm, "    ")).join("\n\n"));
    css.push("  }");
    css.push("}");
  }
  const cssText = `${css.join("\n")}\n`;

  // virtu.tailwind.css
  const tw: string[] = [GENERATED_HEADER];
  tw.push(`/* Tailwind v4 theme for ${loaded.name}. Import it after tailwindcss and virtu.css. */`);
  tw.push("@theme inline {");
  const twSorted = [...twNames.entries()].sort(([x], [y]) => byCodeUnit(x, y));
  for (const [name, { name: prop }] of twSorted) tw.push(`  ${name}: var(${prop});`);
  tw.push("}");
  const twText = `${tw.join("\n")}\n`;

  // virtu.tokens.json
  const doc: JsonObject = {
    $generated: "Generated by virtu build. Do not edit.",
    virtu: "0",
    system: loaded.name,
    contexts: contexts.map((c) => ({ name: c.name, dialect: c.dialect, values: c.values, default: c.default, attribute: `data-${c.name}` })),
    permutations: a.permutations.map((p) => {
      const r = a.resolution(p);
      const entries: JsonObject = {};
      for (const path of [...r.tokens.keys()].sort(byCodeUnit)) {
        const token = r.tokens.get(path);
        if (!token) continue;
        const v = cssValue(token);
        const entry: JsonObject = { type: token.type, value: canonicalValue(token), property: v.css === null ? null : cssName(path), css: v.css };
        if (v.css !== null && v.wide !== undefined) entry["cssWide"] = v.wide;
        entries[path] = entry;
      }
      return { contexts: { ...p }, tokens: entries };
    }),
    notes: [...notes.values()].sort((x, y) => byCodeUnit(x.token, y.token)).map((n) => ({ token: n.token, type: n.type, note: n.note })),
  };
  const jsonText = `${JSON.stringify(doc, null, 2)}\n`;

  const files: BuildFile[] = [
    { name: "virtu.css", content: cssText },
    { name: "virtu.tailwind.css", content: twText },
    { name: "virtu.tokens.json", content: jsonText },
  ];
  if (shadcn !== null) {
    findings.push(...shadcn.findings);
    files.push({ name: "virtu.shadcn.css", content: shadcnCss(loaded, a, shadcn.variables, shadcn.dark, values, wides) });
  }

  return {
    ok: true,
    files,
    findings,
    notes: [...notes.values()],
    properties: paths.length,
    tailwindNames: twNames.size,
    permutations: a.permutations.length,
    shadcnVariables: shadcn === null ? 0 : shadcn.variables.length,
  };
}

/** shadcn's radius scale, from its theming docs: each step a multiple of --radius. */
const SHADCN_RADII: ReadonlyArray<[string, string]> = [
  ["sm", "calc(var(--radius) * 0.6)"],
  ["md", "calc(var(--radius) * 0.8)"],
  ["lg", "var(--radius)"],
  ["xl", "calc(var(--radius) * 1.4)"],
  ["2xl", "calc(var(--radius) * 1.8)"],
  ["3xl", "calc(var(--radius) * 2.2)"],
  ["4xl", "calc(var(--radius) * 2.6)"],
];

const attribute = (context: string, value: string): string => `[data-${context}="${value.replace(/["\\]/g, (m) => `\\${m}`)}"]`;

/**
 * virtu.shadcn.css. A var() in a custom property is substituted where it is
 * declared and the result inherited, so the aliases are declared on :root and
 * again on every context attribute that changes a mapped token.
 */
function shadcnCss(
  loaded: Loaded,
  a: Analysis,
  variables: ShadcnMap["variables"],
  dark: { context: string; value: string } | null,
  values: Map<string, Values>,
  wides: Map<string, Values>,
): string {
  const tokens = new Set(variables.map((v) => v.token));
  const selectors = [":root"];
  for (const c of contextList(a).filter((x) => x.values.length > 0)) {
    const changes = a.permutations.some((p) =>
      c.values.some((value) => {
        const q = permutationKey({ ...p, [c.name]: value });
        const here = permutationKey(p);
        return [...tokens].some((t) => values.get(q)?.get(t) !== values.get(here)?.get(t) || wides.get(q)?.get(t) !== wides.get(here)?.get(t));
      }),
    );
    if (changes) for (const value of c.values) selectors.push(attribute(c.name, value));
  }
  const lines: string[] = [GENERATED_HEADER];
  lines.push(`/* shadcn/ui theme for ${loaded.name}, from shadcn.virtu.json. Import it after tailwindcss, virtu.css, and virtu.tailwind.css. */`);
  if (dark !== null) {
    lines.push(`/* shadcn's dark: variant follows ${attribute(dark.context, dark.value)}. Set the theme with data-${dark.context} on <html>, not the dark class. */`);
    const sel = attribute(dark.context, dark.value);
    lines.push(`@custom-variant dark (&:where(${sel}, ${sel} *));`);
  }
  lines.push("");
  lines.push(`${selectors.join(",\n")} {`);
  for (const v of variables) lines.push(`  --${v.name}: var(${cssName(v.token)});`);
  lines.push("}");
  lines.push("");
  lines.push("@theme inline {");
  for (const v of variables) if (v.name !== "radius") lines.push(`  --color-${v.name}: var(--${v.name});`);
  if (variables.some((v) => v.name === "radius")) for (const [step, css] of SHADCN_RADII) lines.push(`  --radius-${step}: ${css};`);
  lines.push("}");
  return `${lines.join("\n")}\n`;
}

/**
 * The rules of the guarded Display P3 block. Each rule outside the block is
 * repeated, in the same order, for every token that has a wide value under
 * some permutation, so the cascade between rules works the same inside the
 * block as outside it. A token a rule holds gets its wide value under that
 * rule's permutation, or its plain value where it has no wide one there.
 */
function wideRules(rules: Array<{ selector: string; perm: Permutation; vals: Values }>, wides: Map<string, Values>, values: Map<string, Values>, def: Permutation): Array<{ selector: string; vals: Values }> {
  const widePaths = new Set([...wides.values()].flatMap((v) => [...v.keys()]));
  if (widePaths.size === 0) return [];
  const defWide = wides.get(permutationKey(def)) ?? new Map<string, string>();
  const out: Array<{ selector: string; vals: Values }> = [];
  for (const r of rules) {
    const wide = wides.get(permutationKey(r.perm)) ?? new Map<string, string>();
    const plain = values.get(permutationKey(r.perm)) ?? new Map<string, string>();
    const vals: Values = new Map();
    for (const path of widePaths) {
      const held = r.selector === ":root" ? wide.has(path) : r.vals.has(path) || wide.get(path) !== defWide.get(path);
      if (!held) continue;
      const css = wide.get(path) ?? plain.get(path);
      if (css !== undefined) vals.set(path, css);
    }
    if (vals.size > 0) out.push({ selector: r.selector, vals });
  }
  return out;
}

function rule(selector: string, vals: Values): string {
  const lines = [...vals.entries()].sort(([x], [y]) => byCodeUnit(x, y)).map(([path, css]) => `  ${cssName(path)}: ${css};`);
  return `${selector} {\n${lines.join("\n")}\n}`;
}

/** The --virtu- properties the system defines: the names virtu.css declares. */
export function definedProperties(a: Analysis): Set<string> {
  const out = new Set<string>();
  for (const p of a.permutations) {
    for (const token of a.resolution(p).tokens.values()) {
      if (cssValue(token).css !== null) out.add(cssName(token.path));
    }
  }
  return out;
}
